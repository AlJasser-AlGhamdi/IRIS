def _count(n: int) -> str:
    """An integer with the write-up's thousands separator: 1857 prints as 1{,}857."""
    return f"{n:,}".replace(",", "{,}")


def cohort_rows(root: pathlib.Path) -> list[tuple[str, int | None]]:
    """The rows of Table~\\ref{tab:cohort} as (label, count); a None count marks a panel heading.

    Every count is read from the evaluation artifacts the harness writes, never typed, so the
    table cannot drift from the cohort. The one derived row, active declarations on externally
    testable controls, is the remainder after the lapsed declarations and those on attestation-required rows."""
    from p2c.evaluation import synthetic as syn  # noqa: PLC0415 (heavy import)
    from p2c.evaluation.figures import load_artifact  # noqa: PLC0415 (heavy import)

    summary = load_artifact(root, "evaluation/outputs/summary.json")
    posture = load_artifact(root, "evaluation/outputs/per_posture.json")
    scan = load_artifact(root, "evaluation/outputs/scan_realism.json")
    detection = load_artifact(root, "evaluation/outputs/detection.json")
    con = load_artifact(root, "evaluation/outputs/contradictions.json")
    bands = summary["size_band_counts"]
    sectors = summary["sector_counts"]
    conditions = scan["condition_host_counts"]
    active_testable = (
        con["n_attestations"] - con["n_lapsed_attestations"] - con["n_unrefutable_active_attestations"]
    )
    rows: list[tuple[str, int | None]] = [
        ("Firms by size band", None),
        ("Firms", summary["n_profiles"]),
        ("Small", bands["small"]),
        ("Medium", bands["medium"]),
        ("Firms by sector", None),
    ]
    rows.extend((_SECTOR_LABEL[sector.name], sectors[sector.name]) for sector in syn.SECTORS)
    rows.append(("Firms by posture", None))
    rows.extend((_POSTURE_LABEL[name], posture[name]["n"]) for name in ("strong", "moderate", "weak"))
    rows.extend(
        [
            ("Hosts by scan condition", None),
            ("Hosts", sum(conditions.values())),
            ("Reachable", conditions["reachable"]),
            ("Throttled", conditions["throttled"]),
            ("CDN fronted", conditions["cdn_fronted"]),
            ("Blocked", conditions["blocked"]),
            ("True issues and findings", None),
            ("True issues injected", detection["n_true_findings"]),
            ("Observed by the sensing model", detection["n_detected"]),
            ("Missed", detection["n_missed"]),
            ("False positives added", detection["n_false_alarm"]),
            ("Findings the toolkit receives", summary["n_findings"]),
            ("Tier 3 declarations", None),
            ("Declarations", con["n_attestations"]),
            ("Lapsed or not yet effective", con["n_lapsed_attestations"]),
            ("Active, on attestation-required rows", con["n_unrefutable_active_attestations"]),
            ("Active, on externally testable controls", active_testable),
            ("Of which overstated", con["declarations_only"]["true_contradictions"]),  # declarations only
        ]
    )
    return rows


def render_cohort_table(root: pathlib.Path) -> str:
    """Render Table~\\ref{tab:cohort}: descriptive statistics of cohort A, read from the artifacts."""
    lines: list[str] = []
    for label, count in cohort_rows(root):
        if count is None:
            if lines:  # a little air above every panel heading but the first, as the other panelled tables have
                lines.append("\\addlinespace[2pt]")
            lines.append(f"\\multicolumn{{2}}{{@{{}}l}}{{\\emph{{{label}}}}} \\\\")
        else:
            lines.append(f"{label} & {_count(count)} \\\\")
    body = "\n".join(lines)
    caption = (
        "Descriptive statistics of the synthetic cohort (cohort A)."
    )
    source = "evaluation/outputs/{summary,per_posture,scan_realism,detection,contradictions}.json"
    return f"""{_header("tab_cohort.tex", source)}\\begin{{table}}[!htbp]
\\centering
\\caption{{{caption}}}
\\label{{tab:cohort}}
\\footnotesize
\\renewcommand{{\\arraystretch}}{{1.0}}
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}lr@{{}}}}
\\toprule
Quantity & {{Count}} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def render_sensing_table() -> str:
    """Render Table~\\ref{tab:sensing}: the sensing model's parameters, from the generator's constants."""
    from p2c.evaluation import synthetic as syn  # noqa: PLC0415 (heavy import)

    rows = "\n".join(
        f"{label} & {syn.CONDITION_SHARES[c]:.2f} & {syn.CONDITION_FACTOR_ORIGIN[c]:.2f} & {syn.CONDITION_FACTOR_EDGE[c]:.2f} \\\\"
        for c, label in (("reachable", "Reachable"), ("throttled", "Throttled"), ("cdn_fronted", "CDN fronted"), ("blocked", "Blocked"))
    )
    sens_lo, sens_hi = min(syn.SENSITIVITY.values()), max(syn.SENSITIVITY.values())
    fa_lo, fa_hi = min(syn.FALSE_ALARM.values()), max(syn.FALSE_ALARM.values())
    caption = (
        "The sensing model's parameters, generated from the generator's constants. Share: the probability "
        "that a host takes the scan condition. Origin and edge factor: the multiplier the condition applies to "
        "the sensitivity and false-positive rate of a detector read at the origin server or at the CDN edge "
        "(Table~\\ref{tab:rates}, Site); detectors read from DNS are exempt."
    )
    source = "p2c.evaluation.synthetic (CONDITION_SHARES, CONDITION_FACTOR_ORIGIN, CONDITION_FACTOR_EDGE, COMPETENCE_MIN, COMPETENCE_MAX, SENSITIVITY, FALSE_ALARM)"
    return f"""{_header("tab_sensing.tex", source)}\\begin{{table}}[!htbp]
\\centering
\\caption{{{caption}}}
\\label{{tab:sensing}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{@{{}}l S[table-format=1.2] S[table-format=1.2] S[table-format=1.2]@{{}}}}
\\toprule
Scan condition of a host & {{Share}} & {{Origin factor}} & {{Edge factor}} \\\\
\\midrule
{rows}
\\midrule
\\multicolumn{{4}}{{@{{}}l}}{{\\emph{{Other parameters}}}} \\\\
Scanner competence factor, per firm & \\multicolumn{{3}}{{l}}{{{syn.COMPETENCE_MIN:.2f} to {syn.COMPETENCE_MAX:.2f}}} \\\\
Detector sensitivity, per detector & \\multicolumn{{3}}{{l}}{{{sens_lo:.2f} to {sens_hi:.2f} (Table~\\ref{{tab:rates}})}} \\\\
Detector false-positive rate, per detector & \\multicolumn{{3}}{{l}}{{{fa_lo:.2f} to {fa_hi:.2f} (Table~\\ref{{tab:rates}})}} \\\\
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def render_all(root: pathlib.Path | None = None) -> dict[str, str]:
    """Render the appendix tables and the cohort table, keyed by file name.

    The three appendix tables are pure functions of the generator's constants. The cohort
    table reads the evaluation artifacts under ``root`` (``make reproduce`` writes them), so
    ``root`` is required for it; the figure generators take the same argument.
    """
    if root is None:
        import pathlib as _pathlib  # noqa: PLC0415

        root = _pathlib.Path(__file__).resolve().parents[3]
    return {
        "tab_rates.tex": render_rates_table(),
        "tab_priors.tex": render_priors_table(),
        "tab_regweights.tex": render_regweights_table(),
        "tab_cohort.tex": render_cohort_table(root),
        "tab_sensing.tex": render_sensing_table(),
    }


def write_all(root: pathlib.Path | None, directory: pathlib.Path) -> list[pathlib.Path]:
    """Write both fragments under ``directory`` as UTF-8 with LF endings; return the paths."""
    directory.mkdir(parents=True, exist_ok=True)
    written: list[pathlib.Path] = []
    for name, body in sorted(render_all(root).items()):
        path = directory / name
        path.write_text(body, encoding="utf-8", newline="\n")
        written.append(path)
    return written
